function headSmash(array){
  if(array.length == 0) return "Gym is empty"
  else if(/\d+/g.test(array)) return "This isn't the gym!!"
  return array.map(e => e.replace(/[O]/gi, ' '))
} //Don't leave this line!!

console.log(headSmash([])) //  "Gym is empty"
console.log(headSmash([0,12,345])) // "This isn't the gym!!"
